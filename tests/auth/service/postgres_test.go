package service_test

import (
	"errors"
	"os"
	"testing"
	"time"

	authservice "clinic-backend/internal/auth/service"

	"gorm.io/driver/postgres"
	"gorm.io/gorm"
)

// A temporary table and a single connection isolate this test from the database schema.
func TestSessionServicePostgres(t *testing.T) {
	dsn := os.Getenv("CLINIC_TEST_POSTGRES_DSN")
	if dsn == "" {
		t.Skip("CLINIC_TEST_POSTGRES_DSN is not set")
	}
	gormDB, err := gorm.Open(postgres.New(postgres.Config{DSN: dsn, PreferSimpleProtocol: true}), &gorm.Config{})
	if err != nil {
		t.Fatalf("open postgres: %v", err)
	}
	db, err := gormDB.DB()
	if err != nil {
		t.Fatalf("get SQL database: %v", err)
	}
	db.SetMaxOpenConns(1)
	t.Cleanup(func() { _ = db.Close() })
	_, err = db.Exec(`CREATE TEMPORARY TABLE auth_session (
		id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		token_hash text NOT NULL UNIQUE, staff_id bigint NOT NULL, role varchar(16) NOT NULL,
		csrf_token_hash text NOT NULL, cas_ticket text, expires_at timestamptz NOT NULL, created_at timestamptz)`)
	if err != nil {
		t.Fatalf("create table: %v", err)
	}
	svc := authservice.NewSessionService(db, time.Hour)
	token, csrf, err := svc.Create(42, "staff", "ST-test")
	if err != nil {
		t.Fatalf("create: %v", err)
	}
	sess, err := svc.Get(token)
	if err != nil || sess.StaffID != 42 || sess.CASTicket != "ST-test" || sess.CreatedAt.IsZero() {
		t.Fatalf("get: %+v, %v", sess, err)
	}
	if !svc.ValidateCSRF(token, csrf) || svc.ValidateCSRF(token, "wrong") {
		t.Fatal("CSRF validation failed")
	}
	expiredSvc := authservice.NewSessionService(db, -time.Hour)
	expired, _, err := expiredSvc.Create(43, "admin", "")
	if err != nil {
		t.Fatalf("create expired: %v", err)
	}
	if _, err := svc.Get(expired); !errors.Is(err, authservice.ErrSessionNotFound) {
		t.Fatalf("expired lookup: %v", err)
	}
	if err := svc.DeleteExpired(); err != nil {
		t.Fatalf("delete expired: %v", err)
	}
	if _, err := svc.Get(token); err != nil {
		t.Fatalf("active session removed: %v", err)
	}
	if _, err := db.Exec("UPDATE auth_session SET cas_ticket = NULL, created_at = NULL"); err != nil {
		t.Fatalf("set null fields: %v", err)
	}
	if sess, err = svc.Get(token); err != nil || sess.CASTicket != "" || !sess.CreatedAt.IsZero() {
		t.Fatalf("nullable fields: %+v, %v", sess, err)
	}
	if err := svc.Delete(token); err != nil {
		t.Fatalf("delete: %v", err)
	}
	if _, err := svc.Get(token); !errors.Is(err, authservice.ErrSessionNotFound) {
		t.Fatalf("deleted lookup: %v", err)
	}
}
