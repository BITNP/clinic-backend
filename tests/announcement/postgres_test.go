package announcement_test

import (
	"errors"
	"os"
	"testing"
	"time"

	"clinic-backend/internal/announcement"

	"gorm.io/driver/postgres"
	"gorm.io/gorm"
)

// The temporary table and single connection keep this test isolated from the
// database schema supplied in the DSN.
func TestAnnouncementServicePostgres(t *testing.T) {
	dsn := os.Getenv("CLINIC_TEST_POSTGRES_DSN")
	if dsn == "" {
		t.Skip("CLINIC_TEST_POSTGRES_DSN is not set")
	}
	gormDB, err := gorm.Open(postgres.New(postgres.Config{DSN: dsn, PreferSimpleProtocol: true}), &gorm.Config{})
	if err != nil {
		t.Fatalf("open postgres: %v", err)
	}
	db, err := gormDB.DB()
	if err != nil {
		t.Fatalf("get SQL database: %v", err)
	}
	db.SetMaxOpenConns(1)
	t.Cleanup(func() { _ = db.Close() })
	_, err = db.Exec(`CREATE TEMPORARY TABLE clinic_announcement (
		id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		title varchar(20) NOT NULL, content text NOT NULL, tag varchar(16) NOT NULL,
		enabled boolean NOT NULL, created_time timestamptz NOT NULL,
		last_edited_time timestamptz NOT NULL, expire_date date NOT NULL,
		priority bigint NOT NULL, brief varchar(64) NOT NULL)`)
	if err != nil {
		t.Fatalf("create table: %v", err)
	}
	if _, err := db.Exec(`CREATE UNIQUE INDEX test_tos_unique ON clinic_announcement(tag) WHERE tag = 'tos'`); err != nil {
		t.Fatalf("create index: %v", err)
	}
	svc := announcement.NewAnnouncementService(db)
	disabled := false
	future := time.Now().UTC().AddDate(0, 0, 4)
	a, err := svc.Create(announcement.CreateAnnouncementInput{Title: "Disabled", Content: "content", Enabled: &disabled, ExpireDate: future})
	if err != nil || a.ID == 0 || a.Enabled || a.Tag != announcement.AnnouncementTagNormal {
		t.Fatalf("create disabled: %+v, %v", a, err)
	}
	got, err := svc.GetByID(a.ID)
	if err != nil || got.Enabled || got.Title != a.Title {
		t.Fatalf("get: %+v, %v", got, err)
	}
	items, total, err := svc.List(announcement.ListAnnouncementFilter{Tag: announcement.AnnouncementTagNormal, ActiveOnly: true})
	if err != nil || total != 0 || len(items) != 0 {
		t.Fatalf("list disabled: %+v, %d, %v", items, total, err)
	}
	enabled := true
	title := "Updated"
	got, err = svc.Update(a.ID, announcement.UpdateAnnouncementInput{Enabled: &enabled, Title: &title})
	if err != nil || !got.Enabled || got.Title != title {
		t.Fatalf("update: %+v, %v", got, err)
	}
	items, total, err = svc.List(announcement.ListAnnouncementFilter{Tag: announcement.AnnouncementTagNormal, ActiveOnly: true, Page: 1, PageSize: 1})
	if err != nil || total != 1 || len(items) != 1 || items[0].ID != a.ID {
		t.Fatalf("list: %+v, %d, %v", items, total, err)
	}
	tos := announcement.AnnouncementTagTOS
	got, err = svc.Update(a.ID, announcement.UpdateAnnouncementInput{Tag: &tos})
	if err != nil || got.Tag != tos {
		t.Fatalf("update tos: %+v, %v", got, err)
	}
	if _, err := svc.Create(announcement.CreateAnnouncementInput{Tag: tos, ExpireDate: future}); !errors.Is(err, announcement.ErrAnnouncementTOSAlreadyExists) {
		t.Fatalf("duplicate tos: %v", err)
	}
	if got, err = svc.GetTOS(); err != nil || got.ID != a.ID {
		t.Fatalf("get tos: %+v, %v", got, err)
	}
	if err := svc.Delete(a.ID); err != nil {
		t.Fatalf("delete: %v", err)
	}
	if err := svc.Delete(a.ID); !errors.Is(err, announcement.ErrAnnouncementNotFound) {
		t.Fatalf("delete missing: %v", err)
	}
}
